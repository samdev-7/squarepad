class BaseProfile:
    def __init__(self):
        self.bitmap = self._generate_bitmap()

    def _generate_bitmap(self):
        """Generate bitmap from 2D array during initialization."""
        icon_array = self.get_icon_array()
        icon_bitmap = displayio.Bitmap(32, 32, 2)  # 32x32 bitmap with 2 colors (black/white)

        # Validate array dimensions
        if len(icon_array) != 32:
            raise ValueError(f"Icon array must have exactly 32 rows, got {len(icon_array)}")
        
        for i, row in enumerate(icon_array):
            if len(row) != 32:
                raise ValueError(f"Row {i} must have exactly 32 columns, got {len(row)}")
            for j, pixel in enumerate(row):
                if i < 32 and j < 32:  # Safety check
                    icon_bitmap[j, i] = pixel
        return icon_bitmap

    def get_name(self):
        """Return the name of the profile. Keep it as short as possible."""
        raise NotImplementedError("This method should be overridden by subclasses")

    def get_keymap(self):
        """Return a 2D array of the macropad keymap, with top right being KC.NO."""
        raise NotImplementedError("This method should be overridden by subclasses")

    def get_encoder_map(self):
        """Return a tuple of 2 values, one for left and right encoder turns."""
        raise NotImplementedError("This method should be overridden by subclasses")

    def get_color(self):
        """Return a tuple of HSV values (0-255) for the profile color."""
        raise NotImplementedError("This method should be overridden by subclasses")

    def get_icon_array(self):
        """Return a 32x32 2D array of 0s and 1s for the profile icon."""
        raise NotImplementedError("This method should be overridden by subclasses")

    def get_icon(self):
        """Return the generated bitmap for the profile icon."""
        return self.bitmap


